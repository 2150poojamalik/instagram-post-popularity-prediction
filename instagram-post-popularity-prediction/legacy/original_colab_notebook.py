last_index=0
popularity=[]
popularity_class=[]
for i in range (1,1090):
  z=str(i)
  posts=ls.count(z)
  last_index+=posts

  for j in range (last_index-1,last_index-posts-1,-1):
    if j>last_index-6:
      popularity.append('0')
    else:
      sum=0
      avg=0
      for k in range(j+1,j+6):
        sum+=int(likes_count[k])
      avg=sum/5
      if int(likes_count[j])<=avg:
        popularity.append('0')
      else:
        popularity.append('1')
  popularity.reverse()

popularity_class+=popularity
